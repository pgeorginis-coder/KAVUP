-- Προσθήκη πεδίου "τεμάχια ανά κιβώτιο" στα προϊόντα
-- Χρησιμοποιείται μόνο για Χυμοί / Αναψυκτικά / Άλλα, ώστε η παραγγελία
-- να προτείνεται σε πλήρη κιβώτια αντί για μεμονωμένα τεμάχια.

ALTER TABLE products ADD COLUMN IF NOT EXISTS crate_size integer;

COMMENT ON COLUMN products.crate_size IS 'Τεμάχια ανά κιβώτιο. NULL = παραγγελία σε μεμονωμένα τεμάχια.';
